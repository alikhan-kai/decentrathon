"""Your solution.

The harness imports this package and calls `apply()` once, in the same process as `soup train`,
before Soup builds the model and the trainer. Patch whatever you need (transformers, peft,
bitsandbytes, Soup itself) so the training run uses your Triton kernels.

The rules in short (the README and the task statement have the full ones):
- your own `@triton.jit` kernels, defined in this folder, run in every measured run and together
  take >= 5% of the training time; the example's kernels (however renamed or rewritten) and
  kernels generated by torch.compile do not count;
- no ready-made kernel libraries (unsloth, liger-kernel, xformers, flash-attn, torchao, ...);
- the task stays the same: model, data, batches and their order, steps, LoRA, optimizer, Soup's
  settings and outputs; no other GPU, no background processes, no tricks with the measurement.

Layout: every module in MODULES has `ENABLED` (bool) and `patch()` (idempotent). apply() calls the
patch of each enabled module. An exception in patch() is NOT swallowed: a patch that silently does
not work is worse than a crash.
"""

import importlib
import sys
import time

MODULES = ["swiglu", "head_loss", "rmsnorm", "nf4", "lora", "overhead"]


def apply():
    t_start = time.perf_counter()
    timings = {}
    for name in MODULES:
        t0 = time.perf_counter()
        module = importlib.import_module(f"{__name__}.{name}")
        t_import = time.perf_counter() - t0

        is_enabled = getattr(module, "ENABLED", False)
        t_patch = 0.0
        if is_enabled:
            patch = getattr(module, "patch", None)
            if patch is not None:
                tp0 = time.perf_counter()
                patch()
                t_patch = time.perf_counter() - tp0
        timings[name] = {
            "import_s": round(t_import, 4),
            "patch_s": round(t_patch, 4),
            "enabled": is_enabled,
        }

    total_apply = time.perf_counter() - t_start
    print(
        f"[overhead] solution.apply() total: {total_apply:.3f}s",
        file=sys.stderr,
    )
    for mod, data in timings.items():
        print(
            f"  - {mod:10s} (enabled={data['enabled']}): import={data['import_s']:.4f}s, patch={data['patch_s']:.4f}s",
            file=sys.stderr,
        )
